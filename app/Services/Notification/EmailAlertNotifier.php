<?php

namespace App\Services\Notification;

use App\Models\AlertIncident;
use App\Models\AlertRule;
use App\Models\SystemSetting;
use Illuminate\Support\Facades\Log;
use Illuminate\Support\Facades\Mail;

class EmailAlertNotifier implements AlertNotifierInterface
{
    public function channelName(): string
    {
        return 'email';
    }

    public function send(AlertIncident $incident, ?AlertRule $rule = null): bool
    {
        $recipient = $rule?->recipients ?: SystemSetting::getValue('notification_email', 'soc-alerts@103.72.109.7');
        if (!$recipient) {
            return false;
        }

        $recipients = array_filter(array_map('trim', explode(',', $recipient)));
        $subject = sprintf('[SentinelLog %s] %s (%s)', strtoupper($incident->severity), $incident->title, $incident->source_host ?: 'system');
        $body = implode("\n", [
            "SentinelLog Security & Operations Alert",
            "=======================================",
            "Title:       {$incident->title}",
            "Severity:    " . strtoupper($incident->severity),
            "Source Host: " . ($incident->source_host ?: 'N/A'),
            "Source IP:   " . ($incident->source_ip ?: 'N/A'),
            "Matches:     {$incident->match_count}",
            "Triggered:   {$incident->triggered_at?->toIso8601String()}",
            "",
            "Summary:",
            $incident->summary,
            "",
            "Note: This alert was generated by syslog pattern/threshold analysis.",
        ]);

        try {
            Mail::raw($body, function ($message) use ($recipients, $subject) {
                $message->to($recipients)->subject($subject);
            });
            return true;
        } catch (\Throwable $e) {
            Log::warning('EmailAlertNotifier failed: ' . $e->getMessage());
            return false;
        }
    }
}
